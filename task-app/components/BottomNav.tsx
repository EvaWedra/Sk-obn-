"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

export default function BottomNav({ isAdmin }: { isAdmin: boolean }) {
  const pathname = usePathname();

  const items = [
    { href: "/", label: "Domov", icon: HomeIcon },
    { href: "/archive", label: "Archív", icon: ArchiveIcon },
    { href: "/notifications", label: "Notifikácie", icon: BellIcon },
    ...(isAdmin ? [{ href: "/admin", label: "Admin", icon: AdminIcon }] : []),
  ];

  return (
    <nav className="fixed bottom-0 left-0 right-0 bg-white dark:bg-gray-900 border-t border-gray-200 dark:border-gray-800 z-50 pb-safe shadow-lg">
      <div className="flex max-w-md mx-auto">
        {items.map(({ href, label, icon: Icon }) => {
          const isActive = href === "/" ? pathname === "/" : pathname.startsWith(href);
          return (
            <Link
              key={href}
              href={href}
              className={`flex-1 flex flex-col items-center justify-center py-2 gap-0.5 text-xs transition-colors ${
                isActive ? "text-brand-600 dark:text-brand-400 font-semibold" : "text-gray-500 dark:text-gray-400"
              }`}
            >
              <Icon className={`w-5 h-5 ${isActive ? "text-brand-600 dark:text-brand-400" : "text-gray-400"}`} />
              <span>{label}</span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}

